def glyph_columns(ch):
    rows = GLYPHS.get(ch)
    cols = []
    for x in range(8):
        byte = 0
        if rows:
            for y in range(7):
                if x < len(rows[y]) and rows[y][x] == 'X':
                    byte |= 1 << y
        cols.append(byte)
    return cols


def main():
    lines = ['/* Auto-generated by scripts/genfont.py - do not edit. */',
             '#include "font8x8_basic.h"', '',
             'const uint8_t font8x8_basic_tr[128][8] = {']
    for code in range(128):
        cols = glyph_columns(chr(code) if code < 128 else ' ')
        entries = ', '.join('0x%02X' % b for b in cols)
        comment = chr(code) if 32 < code < 127 else ' '
        lines.append('    { %s }, /* 0x%02X %s */' % (entries, code, comment))
    lines.append('};')
    path = sys.argv[1] if len(sys.argv) > 1 else 'examples/oled_hello/main/font8x8_basic.c'
    with open(path, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
